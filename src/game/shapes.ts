/**
 * Returns CSS mask-image styles for clipping an element by the SVG shape.
 */
export const getShapeMaskStyle = (shapeId: AvatarShape): React.CSSProperties => {
  const shape = getShapeDefinition(shapeId);
  return {
    WebkitMaskImage: `url('${shape.fileSrc}')`,
    maskImage: `url('${shape.fileSrc}')`,
    WebkitMaskSize: 'contain',
    maskSize: 'contain',
    WebkitMaskRepeat: 'no-repeat',
    maskRepeat: 'no-repeat',
    WebkitMaskPosition: 'center',
    maskPosition: 'center',
  };
};
